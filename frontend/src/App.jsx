import { useEffect, useState } from 'react'
import MetricCard from './components/MetricCard.jsx'
import IssueTable from './components/IssueTable.jsx'

export default function App() {
  const [data, setData] = useState(null)
  const [error, setError] = useState(null)

  useEffect(() => {
    fetch('/data.json')
      .then((r) =>
        r.ok
          ? r.json()
          : Promise.reject(new Error('No data yet — ask your AI client to run generate_dashboard')),
      )
      .then((d) => (d.error ? setError(d.error) : setData(d)))
      .catch((e) => setError(e.message))
  }, [])

  return (
    <div className="page">
      <header>
        <h1>Sprint Health Dashboard</h1>
        {data && <span className="generated">Generated {data.generated_at}</span>}
      </header>

      {error && <div className="banner error">{error}</div>}
      {!error && !data && <div className="banner">Loading dashboard data…</div>}

      {data && (
        <>
          <section className="cards">
            <MetricCard label="Total Points" value={data.total_points} />
            <MetricCard label="Done Points" value={data.done_points} />
            <MetricCard label="Velocity" value={`${data.velocity}%`} accent />
            <MetricCard label="Issue Count" value={data.issue_count} />
            <MetricCard label="Completed Issues" value={data.completed_count} />
          </section>
          <IssueTable issues={data.issues} />
        </>
      )}

      <footer>Generated by TPM Dashboard MCP · Prototype</footer>
    </div>
  )
}
